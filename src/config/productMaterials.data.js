/**
 * Returns a category by slug or undefined
 */
export const getCategoryBySlug = (slug) => {
  if (!slug) return undefined;
  const s = slug.toLowerCase();
  if (PRODUCT_CATEGORIES[s]) return PRODUCT_CATEGORIES[s];
  if (s === 'forged-fittings') return PRODUCT_CATEGORIES['forging'];
  return undefined;
};

