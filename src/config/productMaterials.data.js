// Dynamically glob all asset images so Vite bundles them with hashed production URLs
const assetImages = import.meta.glob('/src/assets/**/*.{jpg,jpeg,png,webp,avif}', {
  eager: true,
  import: 'default',
});

/**
 * Helper to safely resolve image paths from assetImages glob
 */
const resolveAsset = (partialPath) => {
  // Normalize forward slashes
  const normalized = partialPath.replace(/\\/g, '/');
  for (const key of Object.keys(assetImages)) {
    if (key.toLowerCase().endsWith(normalized.toLowerCase())) {
      return assetImages[key];
    }
  }
  for (const key of Object.keys(assetImages)) {
    if (key.toLowerCase().includes(normalized.toLowerCase())) {
      return assetImages[key];
    }
  }
  // Fallback to first available key containing the filename ONLY if no directory path was specified
  if (!normalized.includes('/')) {
    const fileName = normalized.toLowerCase();
    for (const key of Object.keys(assetImages)) {
      if (key.toLowerCase().includes(fileName)) {
        return assetImages[key];
      }
    }
  }
  return '';
};

